import test from 'node:test';
import assert from 'node:assert/strict';
import { createInitialState, getBehaviorIssueCount, BEHAVIOR_ISSUES } from '../data.js';
import { actorForAccount,applySchoolCommand,visibleState } from '../support-server.js';
import { schoolPublications,schoolPublicationPage } from '../activity.js';
import { academicStrategies,behavioralStrategies } from '../tier-rules.js';
const now=Date.parse('2026-11-04T04:00:00Z');
const command=(s,id,a,p,at=now)=>applySchoolCommand(s,actorForAccount(s,id),a,p,at);
const behavior={studentIds:['random1'],issueIds:['tardiness'],description:'Late arrival',incidentDate:'2026-11-04',incidentTime:'13:15',location:'Classroom'};
test('prior offense counts and code actions are per student and issue and ignore forged occurrence/tier overrides',()=>{
 let s=createInitialState();s.behaviorConcerns=[];
 s=command(s,'david','concern-add',{type:'behavior',input:behavior});
 s=command(s,'francois','concern-add',{type:'behavior',input:behavior});
 assert.equal(getBehaviorIssueCount(s,'random1','tardiness'),2);
 assert.equal(getBehaviorIssueCount(s,'random2','tardiness'),0);
 assert.equal(getBehaviorIssueCount(s,'random1','classroom-misconduct'),0);
 const tier2=BEHAVIOR_ISSUES.find(i=>i.level===2).id;
 s=command(s,'david','concern-add',{type:'behavior',input:{...behavior,studentIds:['random1','random2'],issueIds:['tardiness',tier2],occurrence:99,tier:1,strategies:[behavioralStrategies(1)[0].options[0],behavioralStrategies(2)[0].options[0]]}});
 const record=s.behaviorConcerns.at(-1);
 assert.deepEqual(record.tiers,[1,2]);assert.equal(record.automaticOccurrence,true);
 assert.equal(record.codeActions.find(a=>a.studentId==='random1'&&a.issueId==='tardiness').occurrence,3);
 assert.equal(record.codeActions.find(a=>a.studentId==='random2'&&a.issueId==='tardiness').occurrence,1);
 assert.equal(record.codeActions.find(a=>a.studentId==='random1'&&a.issueId===tier2).occurrence,1);
 assert.equal(getBehaviorIssueCount(s,'random1','tardiness'),3);
 assert.equal(getBehaviorIssueCount(s,'random2','tardiness'),1);
 s=command(s,'david','concern-add',{type:'behavior',input:{...behavior,issueIds:[],otherIssueTiers:[2],additionalIssueDetails:'Unlisted issue'}});
 assert.equal(s.behaviorConcerns.at(-1).tier,2);assert.equal(s.behaviorConcerns.at(-1).title,'Other issue not listed');
});
test('academic prevention selections are stored separately from actions already taken and validated against the tier/profile',()=>{
 let s=createInitialState();const choices=academicStrategies(1);
 const input={studentIds:['random1'],tier:1,issueIds:['Low assessment scores'],description:'Observation',incidentDate:'2026-11-04',actionDetails:'Support provided',strategies:[choices[0]],furtherStrategies:[choices[1],'other'],furtherDetails:'Planned review next week'};
 s=command(s,'david','concern-add',{type:'academic',input});
 assert.deepEqual(s.academicConcerns.at(-1).strategies,[choices[0]]);
 assert.deepEqual(s.academicConcerns.at(-1).furtherStrategies,[choices[1],'Other']);
 assert.equal(s.academicConcerns.at(-1).furtherDetails,input.furtherDetails);
 assert.throws(()=>command(s,'david','concern-add',{type:'academic',input:{...input,furtherStrategies:['Not a linked strategy']}}));
});
test('school publication feed includes all staff creations once, paginates after filtering, and never reaches students',()=>{
 let s=createInitialState();s.awards=[];s.activityEvents=[];
 for(let i=0;i<23;i++)s=command(s,i%2?'david':'francois','award-add',{studentId:i%2?'random1':'random2',valueId:'community',points:10},now+i*1000);
 s=command(s,'david','concern-add',{type:'behavior',input:{...behavior,deductionPoints:10,deductionValueIds:['community']}},now+30000);
 const who=actorForAccount(s,'david');const all=schoolPublications(s,who);
 assert.equal(all.length,24);assert.equal(all[0].type,'behavior');
 assert.equal(new Set(all.map(e=>e.id)).size,24);
 assert.equal(schoolPublicationPage(all,{},0).entries.length,10);
 assert.equal(schoolPublicationPage(all,{},1).entries.length,10);
 assert.equal(schoolPublicationPage(all,{},2).entries.length,4);
 assert.equal(schoolPublicationPage(all,{type:'recognition'}).total,23);
 assert.equal(schoolPublicationPage(all,{studentId:'random1'}).total,12);
 const student=s.students.find(p=>p.id==='random1');
 assert.equal(schoolPublicationPage(all,{studentId:'random1',house:student.houseId,grade:String(student.grade),from:'2026-11-04',to:'2026-11-04'}).total,12);
 assert.equal(schoolPublicationPage(all,{from:'2026-11-05'}).total,0);
 const view=visibleState(s,who);
 assert.equal(view.schoolPublications.length,24);assert.ok(view.activityEvents.every(e=>e.actorId==='david'));
 assert.equal(visibleState(s,actorForAccount(s,'random1')).schoolPublications,undefined);
 assert.deepEqual(schoolPublications(s,actorForAccount(s,'random1')),[]);
 // Edits don't add a publication, and removing a coin retains its original publication in the ledger.
 const award=s.awards.find(a=>a.sourceType!=='behavior-concern');
 s=command(s,'francois','award-update',{id:award.id,changes:{comment:'Edited'}},now+40000);
 s=command(s,'francois','award-remove',{id:award.id},now+50000);
 assert.equal(schoolPublications(s,who).length,24);
});

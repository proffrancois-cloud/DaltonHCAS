import test from 'node:test';
import assert from 'node:assert/strict';
import { createInitialState, getCalendarEvents } from '../data.js';
import { applySchoolCommand, actorForAccount, visibleState } from '../support-server.js';
import { trustedAdultIds, pendingTrustedAdults } from '../support-rules.js';
import { renderTrustedAdults } from '../support-ui.js';
import { renderFollowupNotifications } from '../followup-ui.js';
import { renderLeadershipWorkspace, renderEventActivities } from '../leadership-ui.js';
import { canPublishEventActivity } from '../leadership.js';
const now=Date.parse('2026-11-04T00:00:00Z');
const command=(s,id,a,p)=>applySchoolCommand(s,actorForAccount(s,id),a,p,now);
test('trusted adult requests notify only the requested adult; confirmation activates the link and notifies the student once',()=>{
 let s=createInitialState();
 s=command(s,'random1','trusted-adult-add',{teacherId:'david'});
 const request=pendingTrustedAdults(s.students[0])[0];
 assert.deepEqual(trustedAdultIds(s.students[0]),[]);
 assert.deepEqual(s.notifications.at(-1).recipientIds,['david']);
 assert.match(renderTrustedAdults(s,actorForAccount(s,'random1'),s.students[0],String),/Awaiting confirmation/);
 assert.match(renderFollowupNotifications(visibleState(s,actorForAccount(s,'david')),actorForAccount(s,'david'),String),/data-action="confirm-trusted-adult"/);
 s=command(s,'random1','trusted-adult-add',{teacherId:'david'});
 assert.equal(s.notifications.length,1);
 s=command(s,'francois','award-add',{studentId:'random1',valueId:'community',points:10});
 assert.equal(s.notifications.at(-1).recipientIds.includes('david'),false);
 for(const who of ['random1','random2','francois'])assert.throws(()=>command(s,who,'trusted-adult-confirm',{requestId:request.id}));
 s=command(s,'david','trusted-adult-confirm',{requestId:request.id});
 assert.deepEqual(trustedAdultIds(s.students[0]),['david']);
 assert.equal(pendingTrustedAdults(s.students[0]).length,0);
 assert.equal(s.notifications.at(-1).kind,'trusted-adult-confirmed');
 assert.deepEqual(s.notifications.at(-1).recipientIds,['random1']);
 assert.ok(s.notifications.find(n=>n.requestId===request.id).readBy.david);
 const count=s.notifications.length;
 s=command(s,'david','trusted-adult-confirm',{requestId:request.id});
 assert.equal(s.notifications.length,count);
 assert.match(renderFollowupNotifications(visibleState(s,actorForAccount(s,'random1')),actorForAccount(s,'random1'),String),/David confirmed as your trusted adult/);
 s=command(s,'francois','award-add',{studentId:'random1',valueId:'community',points:10});
 assert.equal(s.notifications.at(-1).recipientIds.includes('david'),true);
});
test('legacy selection cannot bypass confirmation, cancelled requests cannot be accepted, and confirmed legacy links remain valid',()=>{
 let s=createInitialState();s.students[0].trustedAdultId='francois';
 s=command(s,'random1','trusted-adult',{teacherIds:['francois','david']});
 assert.deepEqual(trustedAdultIds(s.students[0]),['francois']);
 const request=pendingTrustedAdults(s.students[0])[0];
 s=command(s,'random1','trusted-adult-remove',{teacherId:'david'});
 assert.equal(s.notifications.find(n=>n.requestId===request.id).cancelled,true);
 assert.throws(()=>command(s,'david','trusted-adult-confirm',{requestId:request.id}));
 s=command(s,'random1','trusted-adult-add',{teacherId:'david'});
 assert.notEqual(pendingTrustedAdults(s.students[0])[0].id,request.id);
 s=command(s,'random1','trusted-adult-remove',{teacherId:'francois',reason:'Changed preference'});
 assert.equal(s.notifications.at(-1).kind,'trusted-adult-removed');
});
test('members can browse their House and assigned LAB, view day-specific tasks, and cannot publish or modify tasks',()=>{
 let s=createInitialState();
 s.leadershipAssignments.labs=[{id:'assigned-lab',name:'Our lab',leaderIds:['random1'],memberIds:['random2'],teacherIds:['david'],grades:[9],weekday:3}];
 s.customCalendarEvents=[{id:'day-event',title:'Our lab',type:'lab',labId:'assigned-lab',date:'2026-11-04',grades:[]}];
 s=command(s,'david','leader-task-add',{scopeKey:'lab:assigned-lab',leaderIds:['random1'],title:'Prepare materials',description:'Prepare the shared equipment.',deadline:'2026-11-04'});
 s=command(s,'david','leader-task-add',{scopeKey:'lab:assigned-lab',leaderIds:['random1'],title:'Later task',description:'Next session.',deadline:'2026-11-11'});
 const member=actorForAccount(s,'random2'),outsider=actorForAccount(s,'random3');
 const memberState=visibleState(s,member),event=getCalendarEvents(memberState,{user:member}).find(e=>e.id==='day-event');
 assert.equal(memberState.leadershipTasks.length,2);
 assert.equal(visibleState(s,outsider).leadershipTasks.length,0);
 const html=renderLeadershipWorkspace(memberState,member,'lab',String);
 assert.match(html,/Prepare materials/);assert.doesNotMatch(html,/data-support-form=/);
 const popup=renderEventActivities(memberState,member,event,String);
 assert.match(popup,/Tasks for this day/);assert.match(popup,/Prepare materials/);assert.doesNotMatch(popup,/Later task/);
 assert.equal(canPublishEventActivity(s,member,event),false);
 assert.throws(()=>command(s,'random2','event-activity-add',{eventId:event.id,text:'Forged'}));
 assert.throws(()=>command(s,'random2','leader-task-add',{scopeKey:'lab:assigned-lab',leaderIds:['random1'],title:'Forged',description:'X',deadline:'2026-11-04'}));
 assert.match(renderLeadershipWorkspace(visibleState(s,outsider),outsider,'lab',String),/No lab assigned yet/);
 const houseHtml=renderLeadershipWorkspace(visibleState(s,outsider),outsider,'house',String);
 assert.match(houseHtml,/leadership-scope/);assert.doesNotMatch(houseHtml,/data-support-form=/);
 const ranged=renderLeadershipWorkspace(memberState,member,'lab',String,{from:'2026-11-04',to:'2026-11-04'});
 assert.match(ranged,/Prepare materials/);assert.doesNotMatch(ranged,/Later task/);
});

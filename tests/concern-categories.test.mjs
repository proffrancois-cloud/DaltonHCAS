import test from 'node:test';
import assert from 'node:assert/strict';
import { createInitialState, updateConcern, BEHAVIOR_ISSUES } from '../data.js';
import { applySchoolCommand, actorForAccount } from '../support-server.js';
import { concernTitle } from '../concerns-data.js';
import { selOptions } from '../tier-rules.js';
import { selSupportChoices } from '../concern-ui.js';
const publish=(s,type,input)=>applySchoolCommand(s,actorForAccount(s,'david'),'concern-add',{type,input});
const common={studentIds:['random1'],tier:1,description:'Observed situation',incidentDate:'2026-11-04',title:'This free title must be ignored'};
test('concern titles come from selected issues, support multiple selections, and remain authoritative on edit',()=>{
 let s=createInitialState();
 s=publish(s,'behavior',{...common,issueIds:['tardiness','classroom-misconduct'],occurrence:1,incidentTime:'13:15',location:'Classroom'});
 assert.equal(s.behaviorConcerns.at(-1).title,BEHAVIOR_ISSUES.filter(i=>['tardiness','classroom-misconduct'].includes(i.id)).sort((a,b)=>['tardiness','classroom-misconduct'].indexOf(a.id)-['tardiness','classroom-misconduct'].indexOf(b.id)).map(i=>i.title).join(', '));
 s=publish(s,'academic',{...common,issueIds:['Low assessment scores','Lack of organization'],actionDetails:'Small-group support'});
 assert.equal(s.academicConcerns.at(-1).title,'Low assessment scores, Lack of organization');
 const issue=selOptions(1).find(o=>o.title==='Friendship issues');
 const {title,...noTitle}=common;
 s=publish(s,'sel',{...noTitle,concernIds:[issue.id]});
 assert.equal(s.selConcerns.at(-1).title,'Friendship issues');
 s=updateConcern(s,'sel',s.selConcerns.at(-1).id,'david',{title:'Forged title',description:'Updated observation'});
 assert.equal(s.selConcerns.at(-1).title,'Friendship issues');
 assert.equal(concernTitle('behavior',{otherIssueSelected:true}),'Other issue not listed');
 assert.equal(concernTitle('behavior',{issueIds:['tardiness'],otherIssueSelected:false,otherIssue:'Not selected'}),'Tardiness');
 assert.equal(concernTitle('academic',{issueIds:['other'],otherIssue:'A detailed explanation'}),'Other');
 const many=BEHAVIOR_ISSUES.filter(i=>i.level===2).map(i=>i.id);
 const long=publish(s,'behavior',{...common,tier:2,issueIds:many,occurrence:1,incidentTime:'13:15',location:'Classroom'}).behaviorConcerns.at(-1).title;
 assert.ok(long.length>120);assert.equal(long,BEHAVIOR_ISSUES.filter(i=>i.level===2).map(i=>i.title).join(', '));
});
test('SEL suggestions follow current issues, deduplicate shared strategies, and only linked support can be submitted',()=>{
 const options=selOptions(1),a=options.find(o=>o.title==='Friendship issues'),b=options.find(o=>o.title==='Feeling left out');
 const selected=[a.id,b.id],strategies=[...new Set([...a.strategies,...b.strategies])];
 const html=selSupportChoices(options,selected,[strategies[0]],String);
 assert.equal((html.match(/name="strategies"/g)??[]).length,strategies.length);
 assert.match(html,/checked/);assert.equal(selSupportChoices(options,[],[],String),'');
 const s=publish(createInitialState(),'sel',{...common,concernIds:selected,strategies:[strategies[0]]});
 assert.deepEqual(s.selConcerns.at(-1).strategies,[strategies[0]]);
 assert.deepEqual(s.selConcerns.at(-1).recommendedStrategies,strategies);
 assert.throws(()=>publish(s,'sel',{...common,concernIds:[a.id],strategies:['An unrelated intervention']}),/linked/);
 assert.equal(selSupportChoices(options,[a.id],['An unrelated intervention'],String).includes('An unrelated intervention'),false);
});
